<?php

class LDTT_Sample_Data {

    /**
     * Load sample data from JSON file.
     *
     * @return array|null Sample data array or null if file doesn't exist.
     */
    private static function load_sample_data() {
        $file_path = plugin_dir_path( __FILE__ ) . '../../data/learndash-sample-data.json';
        
        if ( ! file_exists( $file_path ) ) {
            return null;
        }
        
        $json_content = file_get_contents( $file_path );
        return json_decode( $json_content, true );
    }

    /**
     * Get random course title from dataset.
     *
     * @return string Random course title.
     */
    public static function get_random_course_title() {
        $data = self::load_sample_data();
        if ( $data && isset( $data['courses']['titles'] ) ) {
            $titles = $data['courses']['titles'];
            return $titles[ array_rand( $titles ) ];
        }
        return 'Sample Course';
    }

    /**
     * Get random course description from dataset.
