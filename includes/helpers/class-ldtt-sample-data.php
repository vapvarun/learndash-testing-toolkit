    /**
     * Create multiple sample groups.
     *
     * @param int $count Number of groups to create.
     * @return array An array of created group IDs.
     */
    public static function create_sample_groups( $count = 5 ) {
        $groups = array();
        
        for ( $i = 1; $i <= $count; $i++ ) {
            $group_id = self::create_sample_group();
            if ( $group_id && ! is_wp_error( $group_id ) ) {
                $groups[] = $group_id;
            }
        }
        
        return $groups;
    }

    /**
     * Create sample questions for a quiz.
     *
     * @param int $quiz_id The ID of the quiz.
