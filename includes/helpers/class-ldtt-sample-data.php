                'post_content' => self::get_random_topic_content(),
                'post_author'  => $admin_id,
                'meta_input'   => array(
                    '_ldtt_test_data' => true,
                ),
            ) );

            if ( ! is_wp_error( $topic_id ) ) {
                // Associate topic with lesson and course
                learndash_update_setting( $topic_id, 'course', $course_id );
                learndash_update_setting( $topic_id, 'lesson', $lesson_id );
                $topics[] = $topic_id;
            }
        }

        return $topics;
    }

    /**
     * Create a sample quiz for a lesson.
